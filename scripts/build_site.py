HOW = """
## How it works

```
list_repos        official GitHub MCP server, read-only toolset
select_repos      Jev scores every repo for "is this claimable"; no Groq tokens
fetch_facts       deterministic: README, tree, commits, tests, CI, dependencies
safety_scan       flags .env / tokens / cookies committed in the repositories
summarize_repo    strict JSON, one repo per call, rate limited
verify_claims     CODE, not a prompt: unsupported claims are dropped
score_roles       deterministic 100-point ATS rubric
build_resumes     bullets drawn only from verified claims
plan_improvements evidence-linked steps with hours and ATS gain
```

### Why claims survive or die

`verify_claims` is plain Python. Every digit in a generated claim must appear
in that repository's evidence bundle, and every supporting quote must be both
present **and** relevant to the claim it backs. A claim that fails is not
softened &mdash; it is dropped, and reappears as a measurement task.

The clearest example from a real run: the model wrote *"losing 745 out of
1484"*, having computed `1484 &minus; 739` itself. The evidence contains 739 and
1484 but never 745, so the claim was refused.

### Measured quality

Claim faithfulness &mdash; the text that actually reaches a resume &mdash; and
number precision both measure **1.00**. Whole-summary faithfulness is **0.83**,
and that gap is reported rather than averaged away: the descriptive
`problem` and `approach` fields are framing, are not run through
`verify_claims`, and can contain fair-sounding inference.

### Operating inside a free tier

The binding constraint is **8,000 tokens per minute**, not the request rate.
One evidence-linked repository summary costs about 2,074 tokens, so the ceiling
is roughly four per minute. Responses are cached by
`(repo, head SHA, prompt version, model)`, so an unchanged repository costs
nothing on a re-run.
"""


def render_markdown(text: str) -> str:
    import markdown

    md = markdown.Markdown(extensions=["tables", "fenced_code", "toc", "sane_lists"])
    body = md.convert(text)
    # Tables must scroll inside their own box, never the page.
    return re.sub(r"(<table>.*?</table>)", r'<div class="scroll">\1</div>', body,
                  flags=re.S)


def strip_html_comments(text: str) -> str:
    return re.sub(r"<!--.*?-->", "", text, flags=re.S)


def cards(meta: dict, trace_json: dict | None) -> str:
    stats: list[tuple[str, str]] = []
    claims = (trace_json or {}).get("claims") or {}
    verified, total = claims.get("verified"), sum(claims.values()) if claims else 0
    if verified is not None and total:
        stats.append((f"{verified}/{total}", "claims verified"))
        stats.append((str(claims.get("rejected", 0)), "claims refused"))
    stats.append((str(meta.get("public_repos_considered", "—")), "public repos scanned"))
    stats.append((str(len(meta.get("repos_in_report") or [])), "repos in this report"))
    tokens = ((trace_json or {}).get("usage") or {}).get("groq", {}).get("total")
    if tokens:
        stats.append((f"{tokens:,}", "Groq tokens for this run"))
    return "".join(
        f'<div class="card"><div class="n">{html.escape(n)}</div>'
        f'<div class="k">{html.escape(k)}</div></div>' for n, k in stats)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default=str(OUT))
    args = ap.parse_args()

    if not REPORT.is_file():
        print(f"missing {REPORT}; run scripts/build_sample.py first")
        return 2
    meta = json.loads(META.read_text()) if META.is_file() else {}
    trace_json_path = SPACE / "assets" / "run_trace.json"
    trace_json = json.loads(trace_json_path.read_text()) if trace_json_path.is_file() else None

    report_html = render_markdown(strip_html_comments(REPORT.read_text()))
    trace_html = (render_markdown(TRACE.read_text()) if TRACE.is_file()
                  else "<p>No run trace recorded.</p>")
    page = PAGE.format(
        description=("Evidence-grounded resumes generated from GitHub repositories. "
                     "Never invents an achievement or a number."),
        cards=cards(meta, trace_json),
        n_repos=len(meta.get("repos_in_report") or []) or "several",
        report=report_html,
        trace=trace_html,
        how=render_markdown(HOW),
    )
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(page)
    print(f"wrote {out.relative_to(ROOT)} ({out.stat().st_size:,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
