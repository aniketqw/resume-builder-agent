"""Regenerate the public sample report that ships with the Space.

The report produced by a normal run is **not** publishable. For `aniketqw` it
draws on 25 repositories, 8 of which are private, and it quotes their READMEs.
Putting that on a public Space would leak private work.

This script re-runs the pipeline over **public repositories only** and writes
`space/assets/sample_report.md`. Repo summaries come from the response cache
keyed by (repo, head SHA, prompt version, model), so the expensive half is
usually free; only the resumes and the plan are regenerated.

    python scripts/build_sample.py --username aniketqw

`scripts/check_sample.py` then asserts that no private repository name survived.
"""
from __future__ import annotations

import argparse
import asyncio
import json
import logging
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from rba.config import Config  # noqa: E402
from rba.github_tools import make_backend  # noqa: E402
from rba.groq_client import GroqClient  # noqa: E402
from rba.nodes.build import build_resumes, comparison_table  # noqa: E402
from rba.nodes.fetch import fetch_facts  # noqa: E402
from rba.nodes.plan import plan_improvements  # noqa: E402
from rba.nodes.safety import safety_scan  # noqa: E402
from rba.nodes.select import select_repos  # noqa: E402
from rba.nodes.summarize import summarize_repos  # noqa: E402
from rba.nodes.verify import verify_claims  # noqa: E402
from rba.report import render_markdown  # noqa: E402
from rba.scoring import load_roles  # noqa: E402
from run_trace import Trace, dump_json, merge, render, write  # noqa: E402

log = logging.getLogger("sample")

OUT = ROOT / "space" / "assets" / "sample_report.md"
MANIFEST = ROOT / "space" / "assets" / "sample_meta.json"
TRACE = ROOT / "run.md"
TRACE_JSON = ROOT / "space" / "assets" / "run_trace.json"

HEADER = """<!-- Generated by scripts/build_sample.py. Do not edit by hand. -->
> **Public sample.** This report was generated from {n} **public** repositories
> belonging to `{user}`. Private repositories are excluded by construction —
> see `scripts/check_sample.py`, which fails the build if a private repository
> name appears here.

"""


def _save_state(path: Path, state: dict, trace) -> None:
    """Checkpoint the pipeline after verification.

    At 8,000 tokens a minute a full run routinely outlives a CI step or a shell
    timeout, and repeating the cached half to reach the uncached half is pure
    waste. Everything here is a Pydantic model or a plain dict, so it round
    trips through JSON without pickling.
    """
    if not path.name:
        raise ValueError("--state PATH is required with --stage facts")
    payload = {
        "username": state.get("username", ""),
        "selected": [r.model_dump(mode="json") for r in state.get("selected", [])],
        "claims": [c.model_dump(mode="json") for c in state.get("claims", [])],
        "summaries": {k: v.model_dump(mode="json")
                      for k, v in (state.get("summaries") or {}).items()},
        "safety": [s.model_dump(mode="json") for s in state.get("safety", [])],
        "errors": state.get("errors") or [],
        "public_considered": state.get("public_considered", 0),
        "usage_partial": (state.get("usage") or {}).get("groq_partial", {}),
        "stages": [vars(s) for s in trace.stages],
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=1, default=str))


def _load_state(path: Path, trace):
    from rba.state import Claim, RepoRef, RepoSummary, SafetyFinding
    from run_trace import Stage

    if not path.is_file():
        raise SystemExit(f"no checkpoint at {path}; run with --stage facts first")
    raw = json.loads(path.read_text())
    trace.stages = [Stage(**s) for s in raw.get("stages", [])]
    state = {
        "username": raw["username"],
        "selected": [RepoRef(**r) for r in raw["selected"]],
        "claims": [Claim(**c) for c in raw["claims"]],
        "summaries": {k: RepoSummary(**v) for k, v in raw["summaries"].items()},
        "safety": [SafetyFinding(**s) for s in raw["safety"]],
        "errors": list(raw.get("errors") or []),
        "public_considered": raw.get("public_considered", 0),
        "usage": {"groq_partial": raw.get("usage_partial") or {}},
    }
    return state, trace


async def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--username", default="aniketqw")
    ap.add_argument("--contact", default="")
    ap.add_argument("--max-repos", type=int, default=0,
                    help="Cap the repo count (0 = use config)")
    ap.add_argument("--state", default="",
                    help="Checkpoint file. The run stops after verification and "
                         "resumes from here, so a rate-limited stage does not "
                         "force the whole pipeline to be repeated.")
    ap.add_argument("--stage", choices=["all", "facts", "resumes"], default="all",
                    help="'facts' stops after verify_claims; 'resumes' resumes "
                         "from the checkpoint.")
    args = ap.parse_args()

    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    for noisy in ("httpx", "httpcore", "mcp", "fastmcp"):
        logging.getLogger(noisy).setLevel(logging.WARNING)

    cfg = Config.load()
    if args.max_repos:
        cfg.raw["selection"]["max_repos"] = args.max_repos
    started = time.time()
    trace = Trace(command=f"python scripts/build_sample.py --username {args.username}",
                  username=args.username)

    if args.stage == "resumes":
        state, trace = _load_state(Path(args.state), trace)
        log.info("resumed from %s with %d claims", args.state, len(state["claims"]))
        return await _finish(args, cfg, state, trace, started)

    backend = await make_backend(cfg)
    try:
        repos = await backend.list_repos(args.username)
        public = [r for r in repos if not r.is_private]
        log.info("%d repositories, %d public — private ones are never fetched",
                 len(repos), len(public))
        trace.stage("list_repos",
                    f"{len(repos)} repositories found via the GitHub MCP server; "
                    f"{len(public)} public. Private repositories are filtered out "
                    f"here, before anything is fetched.")
        state = {"username": args.username, "repos": public,
                 "public_considered": len(public)}
        state = merge(state, await select_repos(state, config=cfg, backend=backend))
        jev = (state.get("usage") or {}).get("jev") or {}
        trace.stage("select_repos",
                    f"Jev scored {jev.get('calls', 0)} repositories for "
                    f"${jev.get('cost_usd', 0):.5f}; kept {len(state['selected'])}. "
                    f"No Groq tokens spent.", calls=jev.get("calls", 0))
        state = merge(state, await fetch_facts(state, backend=backend, config=cfg))
        facts = state.get("facts") or {}
        trace.stage("fetch_facts",
                    f"Deterministic fetch for {len(facts)} repositories "
                    f"({sum(1 for f in facts.values() if f.readme)} with a README, "
                    f"{sum(1 for f in facts.values() if f.has_tests)} with tests). "
                    f"No model involved.")
    finally:
        await backend.aclose()

    state = merge(state, await safety_scan(state))
    trace.stage("safety_scan",
                f"{len(state.get('safety') or [])} finding(s) in the scanned "
                f"repositories.")
    async with GroqClient(cfg) as client:
        state = merge(state, await summarize_repos(state, client=client, config=cfg))
        before = client.usage_report().get("summarize_repo", {}).get("total", 0)
        trace.stage("summarize_repo",
                    f"{len(state.get('summaries') or {})} repositories summarized, "
                    f"{sum(len(s.claims) for s in (state.get('summaries') or {}).values())} "
                    f"raw claims proposed.", tokens=before)
        state = merge(state, await verify_claims(state))
        c = state.get("claims") or []
        nverified = sum(1 for x in c if x.status.value == "verified")
        trace.stage("verify_claims",
                    f"{nverified}/{len(c)} claims survived. Pure Python: no model, "
                    f"no tokens.")
        state["usage"] = {"groq_partial": client.usage_report()}

    if args.stage == "facts":
        _save_state(Path(args.state), state, trace)
        log.info("checkpointed %d claims to %s; run again with --stage resumes",
                 len(state["claims"]), args.state)
        return 0

    return await _finish(args, cfg, state, trace, started)


async def _finish(args, cfg, state, trace, started):
    """Resumes, comparison, plan and rendering — the token-hungry tail."""
    async with GroqClient(cfg) as client:
        state = merge(state, await build_resumes(state, client=client, config=cfg,
                                                 contact=args.contact))
        trace.stage("build_resumes",
                    f"{len(state.get('resumes') or {})} resumes written from "
                    f"verified claims only.",
                    tokens=client.usage_report().get("build_resumes", {}).get("total", 0))
        state["comparison"] = comparison_table(state.get("scores") or {}, load_roles())
        state = merge(state, await plan_improvements(state, client=client, config=cfg))
        trace.stage("plan_improvements",
                    f"{len(state.get('plan') or [])} evidence-linked steps.",
                    tokens=client.usage_report().get("plan_improvements", {}).get("total", 0))
        usage = client.usage_report()
        state["usage"] = {
            "groq": {"total": sum(v["total"] for v in usage.values()),
                     "calls": len(usage), "by_node": usage},
            "cache_hit_rate": client.cache.hit_rate if client.cache else 0.0,
            "elapsed_s": time.time() - started,
        }
    state["contact"] = args.contact

    OUT.parent.mkdir(parents=True, exist_ok=True)
    body = render_markdown(state)
    OUT.write_text(HEADER.format(n=len(state["selected"]), user=args.username) + body)

    MANIFEST.write_text(json.dumps({
        "username": args.username,
        "public_repos_considered": state.get("public_considered",
                                                 len(state.get("selected") or [])),
        "repos_in_report": [r.name for r in state["selected"]],
        "claims_verified": sum(1 for c in state["claims"] if c.status == "verified"),
        "claims_total": len(state["claims"]),
        "groq_tokens": state["usage"]["groq"]["total"],
        "elapsed_s": round(state["usage"]["elapsed_s"], 1),
    }, indent=2) + "\n")

    trace.note("Private repositories are excluded before any fetch, so no "
               "private content enters this pipeline at all.")
    trace.note("Summaries are cached by (repo, head SHA, prompt version, model); "
               "the cache hit rate above shows how much of this run was free.")
    eval_path = ROOT / "evals" / "results" / "latest.json"
    eval_summary = None
    if eval_path.is_file():
        agg = json.loads(eval_path.read_text()).get("aggregate") or {}
        eval_summary = {
            "claim faithfulness (text that reaches a resume)":
                agg.get("claim_faithfulness", "n/a"),
            "number precision": agg.get("number_precision", "n/a"),
            "whole-summary faithfulness (includes unverified prose)":
                agg.get("faithfulness", "n/a"),
            "repositories judged": agg.get("repos", "n/a"),
        }
    write(TRACE, render(trace, state, cfg, eval_summary))
    dump_json(TRACE_JSON, {
        "command": trace.command,
        "stages": [vars(s) for s in trace.stages],
        "usage": state["usage"],
        "claims": {"verified": sum(1 for c in state["claims"] if c.status.value == "verified"),
                   "needs_measure": sum(1 for c in state["claims"] if c.status.value == "needs_measure"),
                   "rejected": sum(1 for c in state["claims"] if c.status.value == "rejected")},
        "scores": {k: v.total for k, v in (state.get("scores") or {}).items()},
    })

    log.info("wrote %s (%d bytes) from %d repos, %d tokens, %.0fs",
             OUT.relative_to(ROOT), OUT.stat().st_size, len(state["selected"]),
             state["usage"]["groq"]["total"], state["usage"]["elapsed_s"])
    log.info("wrote %s", TRACE.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(asyncio.run(main()))
